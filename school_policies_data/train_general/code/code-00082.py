    if not isinstance(zone, (str, unicode, bytes)):
        raise UnknownTimeZoneError(zone)

    if zone.upper() == 'UTC':
        return utc

    try:
        zone = ascii(zone)
    except UnicodeEncodeError:
        # All valid timezones are ASCII
        raise UnknownTimeZoneError(zone)

